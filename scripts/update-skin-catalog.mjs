import { readFile, mkdir, writeFile } from 'node:fs/promises';

const source = 'https://raw.githubusercontent.com/ByMykel/CSGO-API/main/public/api/en/skins.json';
// Pass a downloaded skins.json path for an offline/reproducible refresh.
const input = process.argv[2];
const response = input ? null : await fetch(source);
if (response && !response.ok) throw new Error(`Catalog download failed: ${response.status}`);
const raw = input ? JSON.parse(await readFile(input, 'utf8')) : await response.json();
if (!Array.isArray(raw) || !raw.length) throw new Error('Expected a nonempty skin catalog');
const skins = raw.map((skin) => {
  const defIndex = skin.weapon?.weapon_id;
  const paintIndex = skin.paint_index == null ? null : Number(skin.paint_index);
  if (!skin.name || !Number.isInteger(defIndex) || (paintIndex !== null && !Number.isInteger(paintIndex))) {
    throw new Error(`Invalid identifiers for ${skin.name}`);
  }
  return {
    name: skin.name, weapon: skin.weapon.name, defIndex, paintIndex,
    phase: skin.phase ?? null, minFloat: skin.min_float ?? null,
    maxFloat: skin.max_float ?? null, wears: (skin.wears ?? []).map((wear) => wear.name),
    stattrak: skin.stattrak === true, souvenir: skin.souvenir === true,
  };
}).sort((a, b) => a.defIndex - b.defIndex || (a.paintIndex ?? -1) - (b.paintIndex ?? -1) || a.name.localeCompare(b.name));
const directory = new URL('../src/constants/', import.meta.url);
await mkdir(directory, { recursive: true });
// Small typed batches avoid TypeScript's large object-union inference limit.
const batches = [];
for (let i = 0; i < skins.length; i += 100) batches.push(skins.slice(i, i + 100));
const contents = `// Generated by scripts/update-skin-catalog.mjs. Do not edit manually.\n// Community source: ${source}\nimport type { SkinDefinition } from './skins';\n\n${batches.map((batch, i) => `const batch${i}: readonly SkinDefinition[] = [\n${batch.map((skin) => `  ${JSON.stringify(skin)},`).join('\n')}\n];`).join('\n\n')}\n\nexport const SKIN_CATALOG: readonly SkinDefinition[] = [${batches.map((_, i) => `...batch${i}`).join(', ')}];\n`;
await writeFile(new URL('skinCatalog.generated.ts', directory), contents);
console.log(`Generated ${skins.length} skin entries.`);
